def test_render_has_the_tables() -> None:
    text = render(summary())

    assert "| `gemma3:4b/v3` | 100 % (75 %) | 50 % | 100 % | 50 % | 80 % / 50 % / – |" in text
    assert "`gemma3:4b/v3` vs `gemma3:4b/v2`" in text and "+25 pp" in text and "-0.5" in text
    assert "| `gemma3:4b/v3` | as shipped | derived | 2 | 0 | 0 | 1 | 100 % | 100 % |" in text
    assert "| `gemma3:4b/v3` | extraction flags | hand label | – | – | – | – | – | – |" in text
    assert "| `gemma3:4b/v3` | total_wrong | 2 | c02 |" in text
    assert "| c02 | needs_review * |" in text


def test_render_explains_the_repair_column_and_marks_partial_results() -> None:
    full = render(summary())

    assert "the extractor doesn't say whether a repair happened" in full
    assert "Partial results" not in full
    assert "**Partial results:**" in render({**summary(), "partial": True})


def test_render_is_deterministic_and_handles_an_empty_summary() -> None:
    assert render(summary()) == render(summary())
    empty = render({"today": "2026-10-12", "runs": 1, "configs": [], "comparisons": []})
    assert "No comparison" in empty and "No cases scored." in empty
