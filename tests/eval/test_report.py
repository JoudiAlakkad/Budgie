"""The generated block of docs/evaluation.md (`eval/report.py`)."""

from pathlib import Path
from typing import Any

import pytest

from eval.report import MarkerError, render, replace_block

REPO = Path(__file__).resolve().parents[2]
BEFORE = "# Evaluation\n\nThe student's text, with trailing spaces   \r\nand CRLF.\n\n"
BEGIN = "<!-- eval:begin (generated by eval/run_eval.py; do not edit inside) -->"
END = "<!-- eval:end -->"
AFTER = "\n\n## Conclusions\nWritten by hand. <!-- a comment -->\n"


def doc(inside: str = "\nold\n") -> str:
    return f"{BEFORE}{BEGIN}{inside}{END}{AFTER}"


def test_only_the_block_changes() -> None:
    new = replace_block(doc(), "| a | b |\n|---|---|")

    assert new.startswith(BEFORE + BEGIN)
    assert new.endswith(END + AFTER)
    assert new == f"{BEFORE}{BEGIN}\n| a | b |\n|---|---|\n{END}{AFTER}"


def test_replacing_twice_gives_the_same_text() -> None:
    once = replace_block(doc(), "block")

    assert replace_block(once, "block") == once
    assert replace_block(doc("\n\n\nlots\nof\nold\n"), "block") == once


def test_the_committed_report_has_valid_markers() -> None:
    text = (REPO / "docs" / "evaluation.md").read_text(encoding="utf-8")

    new = replace_block(text, "generated")

    head = text.index("-->", text.index("<!-- eval:begin")) + len("-->")
    assert new[:head] == text[:head]
    assert new[new.index(END) :] == text[text.index(END) :]
    assert "\ngenerated\n" in new


@pytest.mark.parametrize(
    "text",
    [
        "no markers at all",
        f"{BEGIN}\nonly the begin",
        f"only the end\n{END}",
        f"{END}\nend first\n{BEGIN}",
        f"{BEGIN}\n{BEGIN}\n{END}",
        f"{BEGIN}\n{END}\n{END}",
        f"{BEGIN}\n{END}\n{BEGIN}\n{END}",
        f"<!-- eval:begin never closed\n{END}",
    ],
)
def test_bad_markers_raise(text: str) -> None:
    with pytest.raises(MarkerError):
        replace_block(text, "block")


